// ============================================================
// Story Hub - Admin Bridge
// admin.js
// ============================================================
//
// هذا الملف لم يعد يحتوي على منطق تحديد "من هو المسؤول".
// تحديد المسؤول أصبح بالكامل من مسؤولية auth.js عبر:
//   - ADMIN_UID (في database.js)
//   - أو role: "admin" في Realtime Database
//
// لا يوجد هنا أي Firebase Functions ولا Secret Manager،
// التزامًا بالمرحلة المجانية المتفق عليها.
//
// دور هذا الملف الوحيد الآن: توفير واجهة برمجية بديلة
// (window.StoryHubAdmin) لأي كود قديم في الموقع ما زال
// ينادي عليها، بحيث تُحوَّل تلقائيًا إلى window.StoryHubAuth
// الحقيقية بدل تكرار المنطق أو التعارض معه.
// ============================================================


// ============================================================
// مساعد: انتظار جاهزية window.StoryHubAuth
// ============================================================

function getAuthBridge() {

    return window.StoryHubAuth ||
        null;
}


// ============================================================
// فتح لوحة المسؤول
// ============================================================
//
// لا حاجة لأي كود أو نافذة إدخال؛ إن كان المستخدم
// مسجّلاً بحساب المسؤول (أو يحمل role: admin) فسيرى
// زر "لوحة المسؤول" في شريط التنقل تلقائيًا من auth.js.
// هذه الدالة تبقى فقط للتوافق مع أي استدعاء قديم.
// ============================================================

function openAdminPanel() {

    const bridge =
        getAuthBridge();

    if (!bridge) {

        console.warn(
            "⚠️ Story Hub Admin: نظام المصادقة غير جاهز بعد."
        );

        return;
    }

    if (!bridge.isAdmin()) {

        console.warn(
            "⛔ Story Hub Admin: لا توجد صلاحية مسؤول لهذا الحساب."
        );

        return;
    }

    bridge.openAdminPanel();
}


// ============================================================
// حالة المسؤول الحالية
// ============================================================

function isAdmin() {

    const bridge =
        getAuthBridge();

    return bridge
        ? bridge.isAdmin()
        : false;
}


// ============================================================
// تسجيل الخروج (يُفوَّض بالكامل لـ auth.js)
// ============================================================

function logoutAdmin() {

    const bridge =
        getAuthBridge();

    if (bridge) {

        bridge.logout();
    }
}


// ============================================================
// API عامة للتوافق مع الاستدعاءات القديمة
// ============================================================

window.StoryHubAdmin = {

    panel: openAdminPanel,

    isAdmin,

    logout: logoutAdmin

};


